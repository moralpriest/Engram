// - Keep network names in English: Mainnet, Testnet, Simulator
// - If a translated word is too long for a button, abbreviate naturally (e.g., "Configuración" → "Config.")
// - Preserve format verbs like %s and %d in translated strings
// - Preserve markdown formatting (###, *, \n) in translated strings
// - When in doubt, keep the English term rather than creating an awkward translation
