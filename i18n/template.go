//
// 3. Translate all the string values. Keep the keys exactly the same.
//    Example:
//      "main.connect": "Verbinden",  // German translation of "Connect"
//
// 4. In i18n/lang.go, add your language to:
//    a) The availableLanguages map:
//         LangDE: "Deutsch",
//    b) The LanguageOrder() slice (add your code at the end):
//         return []string{LangEN, LangFR, LangES, LangDE}
//    c) The T() function switch statement:
//         case LangDE:
//             translations = stringsDE
//
// 5. Add the language constant in lang.go:
//         const LangDE = "de"
//
